-- Por Acá. Una lectura, no una auditoría general. Solo FULL 05 ART del 31/10.
-- No escritura, no aprobaciones. No inventar reporte si el post-run no persistió.
WITH target AS (
 SELECT r.* FROM radar_definitivo.runs r
 WHERE r.mode='full'
   AND (r.started_at AT TIME ZONE 'America/Argentina/Buenos_Aires')::date=DATE '2026-10-31'
   AND (r.started_at AT TIME ZONE 'America/Argentina/Buenos_Aires')::time>=TIME '04:45'
 ORDER BY r.started_at DESC LIMIT 1
), facts AS (
 SELECT l.listing_key,l.title,l.event_date,l.event_time,l.venue,l.proof_url,
        l.source_id,l.first_run_id,coalesce(s.circuit,'unclassified') AS circuit,
        public.poraca_fact_key_v1(l.title) AS normalized_title,
        public.poraca_fact_key_v1(l.venue) AS normalized_venue,
        public.poraca_first_party_event_detail_v1(
          l.evidence_tier,l.proof_method,l.proof_url) AS original_verified
 FROM radar_definitivo.listing_occurrences l
 JOIN target t ON t.run_id=l.last_run_id
 JOIN radar_definitivo.sources s ON s.source_id=l.source_id
), latest_originals AS (
 SELECT * FROM facts
 WHERE first_run_id=(SELECT run_id FROM target)
   AND event_date>=DATE '2026-10-31'
 ORDER BY CASE WHEN original_verified AND event_time IS NOT NULL
                   AND nullif(btrim(coalesce(venue,'')),'') IS NOT NULL THEN 0 ELSE 1 END,
          event_date,event_time NULLS LAST,title,listing_key LIMIT 12
), same_session_suspicions AS (
 SELECT event_date,event_time,normalized_title,normalized_venue,
        count(*) duplicates,count(DISTINCT source_id) sources,
        jsonb_agg(DISTINCT proof_url) originals
 FROM facts
 WHERE normalized_title IS NOT NULL AND normalized_title<>''
  AND normalized_venue IS NOT NULL AND normalized_venue<>''
  AND event_time IS NOT NULL
 GROUP BY event_date,event_time,normalized_title,normalized_venue
 HAVING count(*)>1
 ORDER BY count(*) DESC,event_date LIMIT 10
), index_only_sources AS (
 SELECT s.source_id,s.name,coalesce(s.circuit,'unclassified') circuit
 FROM radar_definitivo.source_checks c
 JOIN target t ON t.run_id=c.run_id
 JOIN radar_definitivo.sources s ON s.source_id=c.source_id
 WHERE c.status='index_only'
 ORDER BY s.priority DESC,s.name LIMIT 15
)
SELECT jsonb_build_object(
 'schema','poraca-full-05-one-shot-readback-v1',
 'runFound',(SELECT count(*) FROM target)=1,
 'run',(SELECT jsonb_build_object(
   'runId',run_id,'mode',mode,'status',status,'startedAt',started_at,
   'finishedAt',finished_at,'selected',sources_selected,
   'checked',sources_checked,'newUrlCandidates',candidates_new,
   'funnelSaved',summary ? 'editorial_funnel_v1',
   'funnel',summary->'editorial_funnel_v1','health',summary->'health'
  ) FROM target),
 'newOriginalsToReview',(SELECT coalesce(jsonb_agg(jsonb_build_object(
   'key',listing_key,'title',title,'date',event_date,
   'time',event_time,'venue',venue,'circuit',circuit,
   'original',proof_url,'sourceVerified',original_verified
 )),'[]'::jsonb) FROM latest_originals),
 'possibleDuplicatesInRun',(SELECT coalesce(jsonb_agg(jsonb_build_object(
   'date',event_date,'time',event_time,'normalizedTitle',normalized_title,
   'normalizedVenue',normalized_venue,'records',duplicates,
   'sources',sources,'urls',originals
 )),'[]'::jsonb) FROM same_session_suspicions),
 'indexOnlyExamples',(SELECT coalesce(jsonb_agg(jsonb_build_object(
   'sourceId',source_id,'source',name,'circuit',circuit
 )),'[]'::jsonb) FROM index_only_sources),
 'baselineBefore05',jsonb_build_object(
    'staging',627,'canonical',161,'approvedEntities',80,
    'fetchSources',62,'fetchSourcesLabeled',58,'fetchSourcesUnclassified',4),
 'notes',jsonb_build_array(
   '05 FULL measures source inventory, not all city events',
   'revisited does NOT mean duplicate; distinct showtimes do NOT merge',
   'original complete does NOT mean editorial-approved',
   'published matches require canonical and are not generated by Radar',
   'index_only is an evidence coverage gap, not an HTTP failure',
   'a missing funnel means the new report did not persist'
 ),'readOnly',true
) AS result;